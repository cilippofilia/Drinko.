import Foundation

/// How a library card sets its title over the artwork.
enum LibraryCardTitleStyle {
    /// The title sits on a Liquid Glass pill in the card's bottom corner.
    case glassPill
    /// The title sits on a blurred copy of the artwork that fades in from above.
    case blurredBand
}
